const TINTS = {
  verde: '#3f4f36',
  marron: '#5e3f2a',
  gris: '#33373b',
  rosa: '#c98e80',
  azul: '#3a4e6b',
}

function variant(
  slug: string,
  frame: keyof typeof FRAMES,
  tint?: keyof typeof TINTS,
  tryOn = false,
): ProductVariant {
  const base = FRAMES[frame]!
  return {
    id: `${slug}-${frame}`,
    colorName: base.colorName,
    colorFamily: base.colorFamily,
    frameColor: base.frameColor,
    lensTint: tint ? TINTS[tint] : undefined,
    images: [],
    tryOnModelUrl: tryOn ? `/try-on/${slug}-${frame}.glb` : undefined,
  }
}

// Medidas de referencia por forma para el ancho medio: [lente, puente, patilla, alto].
const BASE_MEASURES: Record<FrameShape, [number, number, number, number]> = {
  redondo: [48, 21, 145, 46],
  cuadrado: [52, 19, 145, 44],
  rectangular: [54, 18, 145, 38],
  aviador: [58, 14, 140, 50],
  'ojo-de-gato': [53, 17, 145, 42],
}

const WIDTH_ORDER: FaceWidth[] = ['angosto', 'medio', 'ancho']
const LENS_OFFSET: Record<FaceWidth, number> = { angosto: -2, medio: 0, ancho: 2 }

// Los modelos de acetato se ofrecen en su ancho y en el siguiente; los de metal, en uno solo.
function sizes(shape: FrameShape, material: FrameMaterial, faceWidth: FaceWidth): ProductSize[] {
  const [lens, bridge, temple, height] = BASE_MEASURES[shape]
  const start = WIDTH_ORDER.indexOf(faceWidth)
  const widths = WIDTH_ORDER.slice(start, material === 'acetato' ? start + 2 : start + 1)
  return widths.map((width) => ({
    width,
    lensWidth: lens + LENS_OFFSET[width],
    bridge,
    templeLength: width === 'ancho' ? temple + 5 : temple,
    lensHeight: height + LENS_OFFSET[width] / 2,
  }))
}

